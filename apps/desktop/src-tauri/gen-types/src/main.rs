//! TypeScript types from the committed JSON Schemas. `gen-types <schemas dir> <out.ts>`.
//!
//! The schemas come from `schemars`, so the forms are few: objects, `$ref`, `$defs`, `oneOf` of
//! objects with a `const` tag, `oneOf` of string consts, `anyOf` with null, type arrays.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::{Map, Value};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    let (dir, out) = match (args.next(), args.next()) {
        (Some(d), Some(o)) => (d, o),
        _ => return Err("usage: gen-types <schemas dir> <out.ts>".into()),
    };
    let (ts, report) = generate(Path::new(&dir))?;
    std::fs::write(&out, ts)?;
    println!("{report}");
    Ok(())
}

/// Every named type across the files. Same name with a different body is an error to report.
fn generate(dir: &Path) -> Result<(String, String), Box<dyn std::error::Error>> {
    let mut defs: BTreeMap<String, Value> = BTreeMap::new();
    let mut conflicts = Vec::new();
    let mut files = 0;
    let mut paths: Vec<_> = std::fs::read_dir(dir)?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "json"))
        .collect();
    paths.sort();
    for path in paths {
        let schema: Value = serde_json::from_str(&std::fs::read_to_string(&path)?)?;
        files += 1;
        let title = schema["title"]
            .as_str()
            .ok_or_else(|| format!("{} has no title", path.display()))?
            .to_owned();
        let mut root = schema.clone();
        if let Some(obj) = root.as_object_mut() {
            obj.remove("$defs");
            obj.remove("$schema");
        }
        add(&mut defs, &mut conflicts, title, root);
        if let Some(sub) = schema["$defs"].as_object() {
            for (name, def) in sub {
                add(&mut defs, &mut conflicts, name.clone(), def.clone());
            }
        }
    }
    let mut unknown = Vec::new();
    let mut out = String::from("// Generated by gen-types from docs/reference/schemas. Do not edit.\n");
    for (name, def) in &defs {
        if let Some(text) = def["description"].as_str() {
            doc(&mut out, text, "");
        }
        if let Some(body) = object_body(def, &mut unknown, "") {
            writeln!(out, "export interface {name} {body}\n")?;
        } else {
            let ty = ts_type(def, &mut unknown);
            writeln!(out, "export type {name} = {ty};\n")?;
        }
    }
    let report = format!(
        "{files} files, {} named types, {} conflicting names {:?}, {} forms not handled {:?}",
        defs.len(),
        conflicts.len(),
        conflicts,
        unknown.len(),
        unknown
    );
    Ok((out, report))
}

fn add(defs: &mut BTreeMap<String, Value>, conflicts: &mut Vec<String>, name: String, def: Value) {
    match defs.get(&name) {
        Some(existing) if strip(existing) != strip(&def) => conflicts.push(name),
        Some(_) => {}
        None => {
            defs.insert(name, def);
        }
    }
}

/// A definition without descriptions, to compare two copies of one type.
fn strip(value: &Value) -> Value {
    match value {
        Value::Object(map) => Value::Object(
            map.iter()
                .filter(|(k, _)| !matches!(k.as_str(), "description" | "title"))
                .map(|(k, v)| (k.clone(), strip(v)))
                .collect(),
        ),
        Value::Array(list) => Value::Array(list.iter().map(strip).collect()),
        other => other.clone(),
    }
}

fn doc(out: &mut String, text: &str, indent: &str) {
    let one_line = text.replace("*/", "* /").replace('\n', " ");
    let _ = writeln!(out, "{indent}/** {one_line} */");
}

fn object_body(def: &Value, unknown: &mut Vec<String>, indent: &str) -> Option<String> {
    if def["type"] != "object" {
        return None;
    }
    let props = def["properties"].as_object()?;
    Some(fields(props, def, unknown, indent))
}

fn fields(props: &Map<String, Value>, def: &Value, unknown: &mut Vec<String>, indent: &str) -> String {
    let required: Vec<&str> = def["required"]
        .as_array()
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let inner = format!("{indent}  ");
    let mut out = String::from("{\n");
    for (name, prop) in props {
        if let Some(text) = prop["description"].as_str() {
            doc(&mut out, text, &inner);
        }
        let optional = if required.contains(&name.as_str()) { "" } else { "?" };
        let ty = ts_type(prop, unknown);
        let _ = writeln!(out, "{inner}{name}{optional}: {ty};");
    }
    let _ = write!(out, "{indent}}}");
    out
}

fn ts_type(schema: &Value, unknown: &mut Vec<String>) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        return reference.rsplit('/').next().unwrap_or("unknown").to_owned();
    }
    if let Some(value) = schema.get("const") {
        return value.to_string();
    }
    if let Some(values) = schema["enum"].as_array() {
        return join(values.iter().map(Value::to_string).collect());
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(list) = schema[key].as_array() {
            return join(list.iter().map(|s| ts_type(s, unknown)).collect());
        }
    }
    match &schema["type"] {
        Value::String(t) => primitive(t, schema, unknown),
        Value::Array(list) => join(
            list.iter()
                .filter_map(Value::as_str)
                .map(|t| primitive(t, schema, unknown))
                .collect(),
        ),
        // `true` or `{}`: any JSON value, by design of the schema.
        _ if schema.as_object().is_some_and(|o| o.keys().all(|k| k == "description")) => "unknown".into(),
        _ => {
            unknown.push(schema.to_string().chars().take(80).collect());
            "unknown".into()
        }
    }
}

fn primitive(name: &str, schema: &Value, unknown: &mut Vec<String>) -> String {
    match name {
        "string" => "string".into(),
        "integer" | "number" => "number".into(),
        "boolean" => "boolean".into(),
        "null" => "null".into(),
        "array" => {
            let item = if schema["items"].is_null() {
                "unknown".to_owned()
            } else {
                ts_type(&schema["items"], unknown)
            };
            format!("({item})[]")
        }
        "object" => {
            if let Some(props) = schema["properties"].as_object() {
                return fields(props, schema, unknown, "  ");
            }
            match &schema["additionalProperties"] {
                Value::Null | Value::Bool(_) => "Record<string, unknown>".into(),
                extra => format!("Record<string, {}>", ts_type(extra, unknown)),
            }
        }
        other => {
            unknown.push(format!("type {other}"));
            "unknown".into()
        }
    }
}

fn join(mut parts: Vec<String>) -> String {
    parts.dedup();
    parts.join(" | ")
}
