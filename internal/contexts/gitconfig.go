package contexts

import (
	"fmt"
	"io"
	"path/filepath"
	"sort"
	"strings"
)

type include struct {
	ctx, matcher, cond, path string
	rank                     int // specificity: length of the matcher as Resolve compares it
}

// WriteGitConfig writes includeIf blocks routing each context's git_include.
//
// Git applies every matching include in order and the last value wins, so
// blocks are ordered to mirror Resolve: remote matchers first, path matchers
// last (a path hit beats a remote hit), and within each kind the shorter,
// less specific matcher first (longest prefix wins).
// hasconfig:remote.*.url requires git >= 2.36.
//
// One case cannot be expressed: hasconfig sees remote URLs as written in
// config, before url.<base>.insteadOf rewriting, while Resolve matches the
// rewritten URL. Resolve flags it in Resolution.Warning.
func (c *Config) WriteGitConfig(w io.Writer) error {
	var hosts, paths []include
	for _, ctx := range c.Sorted() {
		if ctx.GitInclude == "" {
			continue
		}
		for _, h := range ctx.Match.Hosts {
			h = strings.ToLower(strings.TrimSuffix(h, "/"))
			for _, pat := range remotePatterns(h) {
				hosts = append(hosts, include{ctx.Name, h, "hasconfig:remote.*.url:" + pat, ctx.GitInclude, len(h)})
			}
		}
		for _, p := range ctx.Match.Paths {
			// Trailing "/" makes git match everything below the directory.
			p = strings.TrimSuffix(p, "/") + "/"
			real := realpath(c.Expand(p))
			paths = append(paths, include{ctx.Name, p, "gitdir:" + p, ctx.GitInclude, len(real)})
			// git resolves symlinks in the repository path but not in the pattern,
			// so a symlinked entry also needs its target, as Resolve compares both resolved.
			if real != filepath.Clean(c.Expand(p)) {
				paths = append(paths, include{ctx.Name, p, "gitdir:" + real + "/", ctx.GitInclude, len(real)})
			}
		}
	}
	bySpecificity := func(s []include) {
		sort.SliceStable(s, func(i, j int) bool { return s[i].rank < s[j].rank })
	}
	bySpecificity(hosts)
	bySpecificity(paths)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `loom context gitconfig` from %s. Do not edit by hand.\n", c.Path)
	b.WriteString("# Order matters: the last matching include wins (remotes < paths, short < long).\n")
	b.WriteString("# Remote URLs match as written in git config: git does not apply url.*.insteadOf\n")
	b.WriteString("# here, so a remote that matches only once rewritten gets no include (`loom context` warns).\n")
	last := ""
	for _, in := range append(hosts, paths...) {
		if head := in.ctx + ": " + in.matcher; head != last {
			fmt.Fprintf(&b, "\n# %s\n", head)
			last = head
		}
		fmt.Fprintf(&b, "[includeIf %q]\n\tpath = %s\n", in.cond, in.path)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// remotePatterns returns hasconfig globs for a "host[/path]" matcher covering
// scp-like (user@host:path), scheme://host/path, scheme://host:port/path,
// scheme://user@host/path and scheme://user@host:port/path URLs. In these
// globs "*" never crosses "/" while "**/" and "/**" span path components.
// Letters become [xX] classes because Resolve ignores case and globs do not.
func remotePatterns(hostPath string) []string {
	host, path, _ := strings.Cut(foldCase(hostPath), "/")
	if path != "" {
		path += "/"
	}
	return []string{
		"*@" + host + ":" + path + "**",
		"**/" + host + "/" + path + "**",
		"**/" + host + ":*/" + path + "**",
		"**/*@" + host + "/" + path + "**",
		"**/*@" + host + ":*/" + path + "**",
	}
}

// foldCase turns each ASCII letter into a "[xX]" glob class.
func foldCase(s string) string {
	var b strings.Builder
	for _, r := range s {
		if lo, up := strings.ToLower(string(r)), strings.ToUpper(string(r)); lo != up {
			b.WriteString("[" + lo + up + "]")
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}
